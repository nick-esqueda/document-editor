#!/usr/bin/env bash
# Makes an extracted release the live one: refreshes secrets, points "current" at it,
# rebuilds and restarts the containers, waits for the API, and cleans up old releases.
# Usage (as root, from deploy-backend.sh via SSM): activate-release.sh <release-id>
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "${SCRIPT_DIR}/paths.sh"

RELEASES_TO_KEEP=3
API_READY_TIMEOUT_SECONDS=120
API_READY_POLL_SECONDS=3
SYSTEMD_UNITS=("ajaia-backup.service" "ajaia-backup.timer")

point_current_at_release() {
  local release_dir="$1"
  ln -sfn "${release_dir}" "${CURRENT_RELEASE_LINK}"
}

start_containers() {
  run_compose up -d --build --remove-orphans
}

# The API answers /api/auth/me with 401 for a logged-out caller once it has migrated and started.
is_api_ready() {
  run_compose exec -T api node -e \
    "fetch('http://localhost:3000/api/auth/me').then((r) => process.exit(r.status === 401 ? 0 : 1)).catch(() => process.exit(1))" \
    > /dev/null 2>&1
}

wait_for_api() {
  local waited_seconds=0
  until is_api_ready; do
    if (( waited_seconds >= API_READY_TIMEOUT_SECONDS )); then
      echo "API not ready after ${API_READY_TIMEOUT_SECONDS}s. Recent logs:" >&2
      run_compose logs --tail 50 api >&2
      exit 1
    fi
    sleep "${API_READY_POLL_SECONDS}"
    waited_seconds=$(( waited_seconds + API_READY_POLL_SECONDS ))
  done
  echo "API is ready"
}

install_backup_timer() {
  local unit
  for unit in "${SYSTEMD_UNITS[@]}"; do
    cp "${SCRIPT_DIR}/systemd/${unit}" "/etc/systemd/system/${unit}"
  done
  systemctl daemon-reload
  systemctl enable --now ajaia-backup.timer
}

remove_old_releases() {
  local old_releases
  # Release folder names are generated by deploy-backend.sh, so ls output is safe to parse.
  # shellcheck disable=SC2012
  old_releases="$(ls -1dt "${RELEASES_DIR}"/*/ | tail -n +$(( RELEASES_TO_KEEP + 1 )))"
  if [[ -n "${old_releases}" ]]; then
    echo "${old_releases}" | xargs rm -rf
  fi
  docker image prune -f > /dev/null
}

activate_release() {
  local release_id="$1"
  local release_dir="${RELEASES_DIR}/${release_id}"

  "${SCRIPT_DIR}/load-secrets.sh"
  point_current_at_release "${release_dir}"

  start_containers
  wait_for_api

  install_backup_timer
  remove_old_releases
  echo "Release ${release_id} is live"
}

activate_release "${1:?Usage: activate-release.sh <release-id>}"
